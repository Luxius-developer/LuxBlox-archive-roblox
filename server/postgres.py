"""PostgreSQL support for the backend's fixed, parameterized SQL queries."""
import ssl
import socket
from urllib.parse import urlsplit


class Connection:
    """Adapt internal SQLite-style placeholders; values stay driver parameters."""
    def __init__(self, connection):
        self.connection = connection

    def execute(self, query, params=()):
        return self.connection.execute(query.replace('?', '%s'), params)


def connection_options(url):
    from psycopg.rows import dict_row
    parsed = urlsplit(url)
    if parsed.scheme not in ('postgres', 'postgresql') or not parsed.hostname:
        raise ValueError('DATABASE_URL must be a PostgreSQL connection URL')
    options = dict(row_factory=dict_row, connect_timeout=10,
                   prepare_threshold=None)
    if parsed.hostname not in ('localhost', '127.0.0.1', '::1'):
        ca_file = ssl.get_default_verify_paths().cafile
        if not ca_file:
            raise RuntimeError('System CA bundle is required for remote PostgreSQL')
        options.update(sslmode='verify-full', sslrootcert=ca_file)
    # Render's network may resolve IPv6 even when it has no IPv6 route.
    # Keep the original hostname for TLS/SNI; hostaddr selects only transport.
    addresses = socket.getaddrinfo(parsed.hostname, parsed.port or 5432, socket.AF_INET, socket.SOCK_STREAM)
    options['hostaddr'] = addresses[0][4][0]
    return options


def create_pool(url):
    from psycopg_pool import ConnectionPool
    return ConnectionPool(url,kwargs=connection_options(url),min_size=0,max_size=8,
                          timeout=10,max_idle=120,name='luxblox',open=True)


def connect(url):
    import psycopg
    connection = psycopg.connect(url, **connection_options(url))
    try:
        connection.execute("SET LOCAL statement_timeout = '10s'")
    except Exception:
        connection.close()
        raise
    return connection


def initialize(connection):
    # Separate statements work with both direct and transaction-pool endpoints.
    connection.execute('''CREATE TABLE IF NOT EXISTS users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username TEXT NOT NULL, salt BYTEA NOT NULL, password_hash BYTEA NOT NULL
    )''')
    connection.execute('CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower ON users (lower(username))')
    connection.execute('''CREATE TABLE IF NOT EXISTS sessions (
        token_hash TEXT PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES users(id), expires BIGINT NOT NULL
    )''')
    connection.execute('CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions(expires)')
