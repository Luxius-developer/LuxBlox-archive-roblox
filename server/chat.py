def initialize(db, is_postgres=False):
    db.execute('''CREATE TABLE IF NOT EXISTS chat_messages (
        id TEXT PRIMARY KEY, sender_id BIGINT NOT NULL REFERENCES users(id),
        recipient_id BIGINT NOT NULL REFERENCES users(id), body TEXT NOT NULL,
        created_at BIGINT NOT NULL, CHECK(length(body) BETWEEN 1 AND 500)
    )''')
    db.execute('CREATE INDEX IF NOT EXISTS chat_sender_time ON chat_messages(sender_id,created_at)')
    db.execute('CREATE INDEX IF NOT EXISTS chat_recipient_time ON chat_messages(recipient_id,created_at)')
    identity = 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' if is_postgres else 'INTEGER PRIMARY KEY'
    db.execute(f'''CREATE TABLE IF NOT EXISTS chat_conversations (
        id {identity},
        user_low BIGINT NOT NULL REFERENCES users(id),
        user_high BIGINT NOT NULL REFERENCES users(id),
        created_at BIGINT NOT NULL,
        UNIQUE(user_low,user_high), CHECK(user_low < user_high)
    )''')


def messages(backend, user_id):
    with backend.connect() as db:
        rows = db.execute('''SELECT m.id,m.sender_id,m.recipient_id,m.body,m.created_at,
            s.username AS sender,r.username AS recipient FROM chat_messages m
            JOIN users s ON s.id=m.sender_id JOIN users r ON r.id=m.recipient_id
            WHERE m.sender_id=? OR m.recipient_id=? ORDER BY m.created_at DESC,m.id DESC LIMIT 100''', (user_id,user_id)).fetchall()
    return [dict(r) for r in reversed(rows)]


def send(backend, user_id, recipient, text):
    if not isinstance(recipient,str) or len(recipient)>20 or not isinstance(text,str):
        raise ApiError(400,'Укажите username получателя и текст.')
    from server.features import preferences
    text=text.strip()
    if not 1<=len(text)<=500 or not all(c.isprintable() or c=='\n' for c in text):
        raise ApiError(400,'Сообщение должно содержать от 1 до 500 видимых символов.')
    with backend.connect() as db:
        row=db.execute('SELECT id FROM users WHERE lower(username)=lower(?)',(recipient,)).fetchone()
        if not row:
            raise ApiError(404,'Получатель не найден.')
        if not preferences(backend,row['id'])['messagesEnabled']:
            raise ApiError(403,'Получатель отключил личные сообщения.')
        if row['id']==user_id:
            raise ApiError(400,'Укажите username другого пользователя.')
        message_id=secrets.token_hex(16)
        db.execute('INSERT INTO chat_messages(id,sender_id,recipient_id,body,created_at) VALUES(?,?,?,?,?)',
                   (message_id,user_id,row['id'],text,time.time_ns()//1000))
    return message_id


def _message_text(text):
    if not isinstance(text, str):
        raise ApiError(400, 'Сообщение должно быть текстом.')
    text = text.strip()
    if not 1 <= len(text) <= 500 or not all(c.isprintable() or c == '\n' for c in text):
        raise ApiError(400, 'Сообщение должно содержать от 1 до 500 видимых символов.')
    return text


def start_conversation(backend, user_id, participant_id):
    try:
        participant_id = int(participant_id)
    except (TypeError, ValueError):
        raise ApiError(400, 'Укажите корректный ID собеседника.') from None
    if participant_id <= 0 or participant_id == user_id:
        raise ApiError(400, 'Нельзя начать чат с этим пользователем.')
    low, high = sorted((user_id, participant_id))
    with backend.connect() as db:
        if not db.execute('SELECT id FROM users WHERE id=?', (participant_id,)).fetchone():
            raise ApiError(404, 'Собеседник не найден.')
        row = db.execute('SELECT id FROM chat_conversations WHERE user_low=? AND user_high=?',
                         (low, high)).fetchone()
        if row is None:
            db.execute('INSERT INTO chat_conversations(user_low,user_high,created_at) VALUES(?,?,?) ON CONFLICT(user_low,user_high) DO NOTHING',
                       (low, high, time.time_ns() // 1000))
            row = db.execute('SELECT id FROM chat_conversations WHERE user_low=? AND user_high=?',
                             (low, high)).fetchone()
    return conversation(backend, row['id'], user_id)


def conversation(backend, conversation_id, user_id):
    try:
        conversation_id = int(conversation_id)
    except (TypeError, ValueError):
        raise ApiError(400, 'Некорректный ID чата.') from None
    with backend.connect() as db:
        row = db.execute('''SELECT c.id,c.user_low,c.user_high,c.created_at,
            a.username AS low_name, b.username AS high_name,
            (SELECT MAX(m.created_at) FROM chat_messages m
             WHERE (m.sender_id=c.user_low AND m.recipient_id=c.user_high)
                OR (m.sender_id=c.user_high AND m.recipient_id=c.user_low)) AS latest_message_at
            FROM chat_conversations c JOIN users a ON a.id=c.user_low
            JOIN users b ON b.id=c.user_high WHERE c.id=?''', (conversation_id,)).fetchone()
    if row is None or user_id not in (row['user_low'], row['user_high']):
        raise ApiError(404, 'Чат не найден.')
    participants = []
    for participant_id, username in ((row['user_low'], row['low_name']),
                                     (row['user_high'], row['high_name'])):
        participants.append({'id': participant_id, 'userId': participant_id,'targetId':participant_id,
                             'username': username, 'displayName': username,
                             'name': username, 'type': 'User'})
    return {'id': row['id'], 'conversationId': row['id'],
            'conversationType': 'OneToOneConversation', 'title': '',
            'participants': participants, 'hasUnreadMessages': False,
            'conversationTitle':{'titleForViewer':'','isDefaultTitle':True},
            'initiator':{'targetId':row['user_low'],'type':'User'},
            'lastUpdated':datetime.fromtimestamp((row['latest_message_at'] or row['created_at'])/1000000, timezone.utc).isoformat().replace('+00:00','Z'),
            'messages': []}


def conversations(backend, user_id, page=1, page_size=20):
    page = max(1, min(10000, int(page)))
    page_size = max(1, min(50, int(page_size)))
    with backend.connect() as db:
        rows = db.execute('''SELECT c.id FROM chat_conversations c
            WHERE c.user_low=? OR c.user_high=?
            ORDER BY COALESCE((SELECT MAX(m.created_at) FROM chat_messages m
                WHERE (m.sender_id=c.user_low AND m.recipient_id=c.user_high)
                   OR (m.sender_id=c.user_high AND m.recipient_id=c.user_low)), c.created_at) DESC, c.id DESC
            LIMIT ? OFFSET ?''', (user_id, user_id, page_size, (page - 1) * page_size)).fetchall()
    return [conversation(backend, row['id'], user_id) for row in rows]


def conversation_messages(backend, conversation_id, user_id, page=1, page_size=50):
    item = conversation(backend, conversation_id, user_id)
    ids = [p['id'] for p in item['participants']]
    page = max(1, min(10000, int(page)))
    page_size = max(1, min(100, int(page_size)))
    with backend.connect() as db:
        rows = db.execute('''SELECT m.id,m.sender_id,m.recipient_id,m.body,m.created_at,
            s.username AS sender,r.username AS recipient FROM chat_messages m
            JOIN users s ON s.id=m.sender_id JOIN users r ON r.id=m.recipient_id
            WHERE ((m.sender_id=? AND m.recipient_id=?) OR
                   (m.sender_id=? AND m.recipient_id=?))
            ORDER BY m.created_at DESC,m.id DESC LIMIT ? OFFSET ?''',
            (ids[0], ids[1], ids[1], ids[0], page_size, (page - 1) * page_size)).fetchall()
    return [{'id': r['id'], 'messageId': r['id'], 'senderTargetId': r['sender_id'],
             'content': r['body'], 'message': r['body'], 'sent': datetime.fromtimestamp(r['created_at']/1000000,timezone.utc).isoformat().replace('+00:00','Z'),
             'read': True, 'messageType': 'PlainText', 'senderType':'User',
             'conversationId':item['id'],'previousMessageId':None,'filteredForReceivers':False,
             'sender': {'id': r['sender_id'], 'name': r['sender']}}
            for r in reversed(rows)]


def send_to_conversation(backend, conversation_id, user_id, text):
    item = conversation(backend, conversation_id, user_id)
    other = next(p for p in item['participants'] if p['id'] != user_id)
    from server.features import preferences
    if not preferences(backend,other['id'])['messagesEnabled']:
        raise ApiError(403,'Получатель отключил личные сообщения.')
    text = _message_text(text)
    return _store_message(backend, user_id, other['id'], text)


def _store_message(backend, sender_id, recipient_id, text):
    message_id = secrets.token_hex(16)
    with backend.connect() as db:
        db.execute('INSERT INTO chat_messages(id,sender_id,recipient_id,body,created_at) VALUES(?,?,?,?,?)',
                   (message_id, sender_id, recipient_id, text, time.time_ns() // 1000))
    return message_id


